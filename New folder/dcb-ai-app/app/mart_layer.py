"""
Read-only access to DCB_Mart/mart_semantic_layer.json (generated by DCB_Mart/build_mart.py; never written here):
table / column docs with units and kinds, the metric registry, capability manifest, known issues, entity lists
and the data period. Cached for the life of the process (restart the server after rebuilding the mart).
"""
from __future__ import annotations

import json
import re
from functools import lru_cache

from app.config import MART_SEMANTIC_PATH


@lru_cache(maxsize=1)
def load() -> dict:
    return json.loads(MART_SEMANTIC_PATH.read_text(encoding="utf-8"))


def fiscal_years() -> list[str]:
    return load()["data_period"]["fiscal_years"]


def latest_fy() -> str:
    return load()["data_period"]["latest_fiscal_year"]


def previous_fy(fy: str) -> str | None:
    fys = fiscal_years()
    i = fys.index(fy) if fy in fys else -1
    return fys[i - 1] if i > 0 else None


@lru_cache(maxsize=1)
def column_info() -> dict[str, dict]:
    """Column name -> {unit, kind, doc}, merged over all mart tables (first definition wins)."""
    out: dict[str, dict] = {}
    for t in load()["tables"].values():
        for c, info in t["columns"].items():
            out.setdefault(c, info)
    return out


@lru_cache(maxsize=1)
def metrics() -> dict[str, dict]:
    return {m["key"]: m for m in load()["metrics"]}


def metric(key: str) -> dict:
    return metrics()[key]


@lru_cache(maxsize=1)
def metric_synonyms() -> list[tuple[str, str]]:
    """(synonym, metric key), longest synonym first."""
    syn = [(s.lower(), m["key"]) for m in load()["metrics"] for s in m["synonyms"]]
    return sorted(syn, key=lambda x: len(x[0]), reverse=True)


def metric_sql(key: str, alias: str | None = None) -> str:
    """The registry expression of one metric as a SELECT expression (ratios as SUM/SUM x scale)."""
    e = metric(key)["expr"]
    # numerator and denominator bracketed: AT&C's numerator is a difference of products
    expr = e["num"] if "den" not in e else f"({e['num']}) * {float(e.get('scale', 1))} / NULLIF(({e['den']}), 0)"
    return f"{expr} AS {alias or key}"


def metric_sql_filtered(key: str, cond: str) -> tuple[str, int]:
    """The registry expression with every SUM(col) restricted to rows matching `cond` (one '?' placeholder each), for
    pivots such as one column per sub-division: (expression, number of times `cond` appears, i.e. parameters to bind)."""
    e = metric(key)["expr"]
    n = 0

    def sub(text: str) -> str:
        nonlocal n
        out, k = re.subn(r"SUM\((\w+)\)", lambda m: f"SUM(CASE WHEN {cond} THEN {m[1]} END)", text)
        n += k
        return out
    num = sub(e["num"])
    if "den" not in e:
        return num, n
    den = sub(e["den"])
    return f"({num}) * {float(e.get('scale', 1))} / NULLIF(({den}), 0)", n


@lru_cache(maxsize=1)
def subdivisions() -> list[dict]:
    return load()["entities"]["subdivisions"]


def geographic_subdivisions() -> list[str]:
    return [s["name"] for s in subdivisions() if s["is_geographic"]]


@lru_cache(maxsize=1)
def families() -> dict[str, dict]:
    return {f["code"]: f for f in load()["entities"]["families"]}


def capabilities() -> list[dict]:
    return load()["capabilities"]


def known_issues() -> list[dict]:
    return load()["known_issues"]


def caveats(families_used: list[str] | None = None, fiscal_years_used: list[str] | None = None,
            subdivisions_used: list[str] | None = None, scopes: list[str] | None = None,
            metrics_used: list[str] | None = None) -> list[str]:
    """The one-line caveats of every known issue this answer touches (see known_issues.json 'affects')."""
    fam, fys, subs, scs = set(families_used or []), set(fiscal_years_used or []), set(subdivisions_used or []), set(scopes or [])
    mets = set(metrics_used or [])
    out = []
    for issue in known_issues():
        if not issue.get("caveat"):
            continue
        hit = False
        for a in issue["affects"]:
            kind, _, rest = a.partition(":")
            if kind == "metric":
                key, _, fy = rest.partition("@")
                hit |= key in mets and (not fy or not fys or fy in fys)
            elif kind == "family":
                code, _, fy = rest.partition("@")
                hit |= code in fam and (not fy or not fys or fy in fys)
            elif kind == "fy":
                hit |= rest in fys
            elif kind == "subdivision":
                hit |= rest in subs
            elif kind == "scope":
                hit |= rest in scs
        if hit:
            out.append(issue["caveat"])
    return out


def norm_family(text: str) -> str | None:
    """'lt1', 'LT 1', 'l.t.-1', 'HT - 2' -> 'LT-1' / 'HT-2' (only the bare family, not a slab like LT-4(a))."""
    m = re.fullmatch(r"\s*([lh])\s*\.?\s*t\s*\.?\s*-?\s*(\d)\s*", text or "", re.I)
    return f"{m[1].upper()}T-{m[2]}" if m else None
